function planFor(industry, category, opportunity, market, profile, research) {
  const text = [opportunity.title, opportunity.action, opportunity.processName, profile?.industry?.label]
    .map(clean).join(' ');
  if (category === 'cost' && /отзыв|репутац|клиентск\w*\s+опыт/i.test(text)) return REVIEW_PROCESS;
  const plans = industry === 'generic' ? genericProcesses(offeringNameFor(market, profile, research)) : PROCESS_PLAYBOOKS[industry];
  const base = plans?.[category] || genericProcesses(offeringNameFor(market, profile, research))[category];
  const variant = asArray(base.variants).find(candidate => candidate.pattern?.test(text));
  return variant || base;
}

function firstNonEmpty(...values) {
  return values.map(asArray).find(value => value.length) || [];
}

function externalItems(key, kinds, market, research) {
  const direct = firstNonEmpty(market?.[key], research?.[key]);
  const derived = asArray(research?.sources).filter(source => kinds.includes(source.kind));
  return firstNonEmpty(direct, derived).filter(item => !EXTERNAL_SOURCE_KINDS.has(item.kind));
}

function evidenceKey(item) {
  return clean(item?.sourceId || item?.url || item?.sourceTitle || item?.quote || item?.title || item?.name);
}

function marketSignals(category, opportunity, plan, market, research) {
  const definitions = [
    { id: 'competitors', label: 'конкуренты', kinds: ['competitor-candidate'] },
    { id: 'reviews', label: 'отзывы', kinds: ['review-snippet'] },
    { id: 'customerEvidence', label: 'критерии выбора клиентов', kinds: ['customer-snippet'] },
    { id: 'industryEvidence', label: 'отраслевой контекст', kinds: ['industry-snippet'] },
    { id: 'marketPriceEvidence', label: 'рыночные ценовые наблюдения', kinds: ['market-price-snippet'] },
  ].map(definition => ({ ...definition, items: externalItems(definition.id, definition.kinds, market, research) }));
  const weights = {
    revenue: { competitors: 2, reviews: 1, customerEvidence: 2, industryEvidence: 1, marketPriceEvidence: 2 },
    cost: { competitors: 0, reviews: 0, customerEvidence: 0, industryEvidence: 0, marketPriceEvidence: 0 },
    offering: { competitors: 2, reviews: 1, customerEvidence: 2, industryEvidence: 1, marketPriceEvidence: 1 },
  }[category];
  const processText = [opportunity.title, opportunity.action, plan.processName, plan.work].map(clean).join(' ');
  if (category === 'cost' && /отзыв|репутац|клиентск\w*\s+опыт/i.test(processText)) {
    weights.reviews = 2;
    weights.customerEvidence = 1;
  }
  let score = 0;
  const present = [];
  for (const signal of definitions) {
    if (!signal.items.length) continue;
    present.push(signal.label);
    const sources = new Set(signal.items.map(evidenceKey).filter(Boolean));
    score += (weights[signal.id] || 0) + (weights[signal.id] && sources.size > 1 ? 1 : 0);
  }
  return { score, present };
}

function catalogAssessment(market, profile, research) {
  const offerings = firstNonEmpty(market?.offerings, profile?.offerings, research?.offerings);
  const named = offerings.filter(item => clean(item.displayName || item.name));
  const sourced = named.filter(item => clean(item.sourceId || item.url) && clean(item.quote || item.description));
  let score = 0;
  if (named.length) score = 1;
  if (named.length && sourced.length === named.length) score += 1;
  if (named.length && named.every(item => clean(item.quote || item.description).length >= 12)) score += 1;
  return {
    score,
    offerings,
    reason: !named.length ? 'каталог не подтверждён' : sourced.length === named.length ? 'карточки имеют источники' : 'полнота источников карточек не подтверждена',
  };
}

function solutionFor(opportunity, plan) {
  const preferred = getSolution(plan.solutionId);
  if (preferred) return { solution: preferred, fit: 'curated' };
  if (plan.allowRecommendation) {
    const recommended = recommendSolution(opportunity);
    if (recommended) return { solution: recommended, fit: 'recommended' };
  }
  return { solution: null, fit: 'process' };
}

function readinessFor(opportunity, plan, profile, research, catalog, signals) {
  const evidence = asArray(opportunity.evidence).filter(item => clean(item.sourceId || item.url) && clean(item.quote));
  const known = [];
  if (evidence.length) known.push('Сохранённые доказательства исходной возможности доступны без изменений.');
  if (profile?.industry?.label || profile?.industry?.id) known.push(`В профиле указано направление «${profile.industry.label || profile.industry.id}».`);
  if (catalog.offerings.length) known.push('В исследовании есть карточки предложений для предметной настройки.');
  if (signals.present.length) known.push(`Есть независимый контекст: ${signals.present.join(', ')}.`);
  const hasLocalDocuments = asArray(research?.sources).some(source => source.kind === 'local-document');
  if (hasLocalDocuments) known.push('В исследование добавлены локальные документы; их пригодность для процесса ещё проверяется.');
  const missing = [
    `Исходный замер по процессу «${plan.processName}» у владельца.`,
    'Обезличенные реальные случаи и эталонные решения ответственного.',
    `Подтверждение владельца: ${plan.owner}`,
    'Подтверждение доступов и способа обмена; перечисленные системы не считаются уже подключёнными.',
  ];
  if (!hasLocalDocuments) missing.push('Внутренние регламенты и данные процесса не представлены в исследовании.');
  return {
    status: known.length ? 'needs-internal-validation' : 'insufficient-evidence',
    known,
    missing,
  };
}

function buildWorkSteps(plan) {
  return [
    { stage: 'input', name: 'Вход', description: plan.input },
    { stage: 'action', name: 'Действия', description: plan.work },
    { stage: 'output', name: 'Результат', description: plan.output },
    { stage: 'escalation', name: 'Эскалация', description: plan.escalation },
  ];
}

function priorityLabel(rank) {
  return ['Первый кандидат на проверку', 'Следующий кандидат', 'После уточнения гипотезы'][rank - 1] || 'Дополнительный кандидат';
}

