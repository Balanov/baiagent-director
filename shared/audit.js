const PROCESS_EVIDENCE_PATTERNS = {
  healthcare: {
    revenue: /запис[а-яё]*\s+(?:на\s+)?(?:при[её]м|анализ|услуг)|онлайн[- ]запис|расписан|напоминан[а-яё]*\s+о\s+(?:при[её]ме|визите)/i,
    offering: /подготовк[а-яё]*\s+(?:к|перед)|как\s+подготов|инструкци[а-яё]*\s+(?:для|к)/i,
  },
  manufacturing: {
    cost: /спецификац|маршрут\s+согласован|производственн[а-яё]*\s+задани|технологическ[а-яё]*\s+(?:карт|процесс)|верси[а-яё]*\s+(?:чертеж|документ)/i,
  },
};

function publishedProcessEvidence(research, pattern) {
  if (!pattern) return [];
  return asArray(research.sources).filter(source => source.kind === 'company-site' || source.kind === 'local-document').flatMap(source => {
    const sentences = String(source.text || '').match(/[^.!?…]+[.!?…]?/g) || [];
    const quote = sentences.map(clean).find(sentence => sentence.length >= 18 && pattern.test(sentence));
    if (!quote) return [];
    const selected = quote.length <= 420 ? quote : clean(quote.slice(0, 417));
    return normalizeEvidenceText(source.text).includes(normalizeEvidenceText(selected))
      ? [{ sourceId: source.id, url: source.url, sourceTitle: source.title, quote: selected, kind: source.kind }] : [];
  }).slice(0, 1);
}

function publishedIndustryEvidence(research, profile) {
  const proof = profile?.industry?.evidence;
  const quote = clean(proof?.quote);
  const pattern = profile?.industry?.pattern;
  const supportedKinds = new Set(['company-site', 'local-document', 'search-snippet', 'review-snippet']);
  const sources = asArray(research.sources).filter(item => supportedKinds.has(item.kind));
  const source = sources.find(item => item.id === proof?.sourceId);
  const verified = (item, text) => normalizeEvidenceText(item.text).includes(normalizeEvidenceText(text))
    ? [{ sourceId: item.id, url: item.url, sourceTitle: item.title, quote: text, kind: item.kind }] : [];
  if (source && quote && (!pattern || pattern.test(quote))) return verified(source, quote);
  for (const item of sources) {
    if (!pattern) continue;
    const sentences = String(item.text || '').match(/[^.!?…]+[.!?…]?/g) || [];
    const descriptive = sentences.map(clean).find(sentence => sentence.length >= 30 && pattern.test(sentence));
    if (descriptive) return verified(item, descriptive.length <= 420 ? descriptive : clean(descriptive.slice(0, 417)));
  }
  return [];
}

export function attachProcessEvidence(opportunities = [], { research = {}, market = {}, profile = {} } = {}) {
  if (!asArray(research.sources).length) return opportunities;
  const industry = industryFor(profile, research);
  return asArray(opportunities).map(opportunity => {
    const category = CATEGORIES.includes(opportunity?.category) ? opportunity.category : null;
    if (!category) return opportunity;
    const plan = planFor(industry, category, opportunity, market, profile, research);
    if (plan === REVIEW_PROCESS) return { ...opportunity, processEvidence: { status: 'customer-experience', note: PROCESS_EVIDENCE_NOTES['customer-experience'] } };
    const processClaim = { processName: plan.processName, processAction: plan.work };
    const originalAndProcessClaim = { ...opportunity, ...processClaim };
    const pattern = plan.evidencePattern || PROCESS_EVIDENCE_PATTERNS[industry]?.[category];
    // A sector-specific pattern defines the new process. The old product title
    // must not make its price proof of an unrelated appointment or handoff.
    const selectionClaim = pattern ? processClaim : originalAndProcessClaim;
    const published = publishedProcessEvidence(research, pattern).filter(proof => {
      const source = asArray(research.sources).find(item => item.id === proof.sourceId);
      const quality = classifyEvidence(processClaim, source, proof.quote);
      return quality.directness === 'direct' && ['published-process', 'internal-document'].includes(quality.evidenceRole);
    });
    const industryEvidence = publishedIndustryEvidence(research, profile);
    // Enrichment must not replace an already verified, process-specific quote
    // with a generic industry source merely because it appears on our own site.
    const selectedEvidence = asArray(opportunity.evidence).filter(proof => {
      const source = asArray(research.sources).find(item => item.id === proof?.sourceId);
      if (!source || (!EXTERNAL_SOURCE_KINDS.has(source.kind) && source.kind !== 'search-snippet')) return false;
      const ownCatalogEvidence = category === 'offering' && EXTERNAL_SOURCE_KINDS.has(source.kind)
        && firstNonEmpty(market?.offerings, research?.offerings).some(item => item.sourceId === proof.sourceId
          && normalizeEvidenceText(item.quote) === normalizeEvidenceText(proof.quote));
      return ownCatalogEvidence || classifyEvidence(selectionClaim, source, proof.quote).relevance === 'relevant';
    }).sort((left, right) => {
      const kind = proof => asArray(research.sources).find(item => item.id === proof?.sourceId)?.kind;
      const rank = proof => {
        const own = EXTERNAL_SOURCE_KINDS.has(kind(proof));
        if (pattern && clean(proof.quote).length >= 35 && pattern.test(proof.quote)) return own ? 0 : 1;
        return own ? 2 : kind(proof) === 'review-snippet' ? 4 : 3;
      };
      return rank(left) - rank(right);
    }).slice(0, 1);
    const evidence = published.length ? published : selectedEvidence.length ? selectedEvidence : industryEvidence;
    const status = published.length ? 'published-process' : 'industry-hypothesis';
    return {
      ...opportunity,
      evidence,
      processEvidence: { status, note: PROCESS_EVIDENCE_NOTES[status] },
      unknowns: unique([...asArray(opportunity.unknowns), !published.length && `Публичное описание процесса «${plan.processName}» не найдено; нужен внутренний регламент.`]).slice(0, 5),
    };
  });
}

export function enrichAuditOpportunities({ opportunities = [], research = {}, market = {}, profile = {} } = {}) {
  const industry = industryFor(profile, research);
  const catalog = catalogAssessment(market, profile, research);
  const prepared = attachProcessEvidence(opportunities, { research, market, profile });
  const enriched = prepared.slice(0, 3).flatMap((opportunity, order) => {
    const category = CATEGORIES.includes(opportunity?.category) ? opportunity.category : null;
    if (!category) return [];
    const plan = planFor(industry, category, opportunity, market, profile, research);
    const { solution, fit } = solutionFor(opportunity, plan);
    const signals = marketSignals(category, opportunity, plan, market, research);
    const ownSources = new Set(asArray(opportunity.evidence).map(evidenceKey).filter(Boolean));
    const ownEvidenceScore = ownSources.size ? Math.min(3, ownSources.size + 1) : 0;
    const solutionScore = solution ? (fit === 'curated' ? 4 : 3) : plan.implementationMode === 'simple-automation' ? 3 : plan.implementationMode === 'data-preparation' ? 2 : 1;
    const score = ownEvidenceScore + signals.score + catalog.score + solutionScore;
    const implementationMode = solution ? 'standard-agent' : IMPLEMENTATION_MODES.has(plan.implementationMode) ? plan.implementationMode : 'custom';
    const readiness = readinessFor(opportunity, plan, profile, research, catalog, signals);
    const evidenceReason = ownSources.size ? 'есть доказательства исходной возможности' : 'доказательства исходной возможности не представлены';
    const signalReason = signals.present.length ? `независимый контекст: ${signals.present.join(', ')}` : 'независимый рыночный контекст не найден';
    const solutionReason = solution ? `решение «${solution.name}» соответствует выбранному процессу` : `выбран режим «${implementationMode}» без натягивания каталожного решения`;
    const base = {
      ...opportunity,
      id: opportunity.id || `opportunity-${category}`,
      processName: plan.processName,
      processAction: plan.work,
      input: plan.input,
      workSteps: buildWorkSteps(plan),
      output: plan.output,
      escalation: plan.escalation,
      owner: plan.owner,
      requiredData: [...plan.requiredData],
      integrations: [...plan.integrations],
      baselineMetrics: [...plan.baselineMetrics],
      qualityMetrics: [...plan.qualityMetrics],
      businessMetric: plan.businessMetric,
      simpleAlternative: plan.simpleAlternative,
      implementationMode,
      solutionId: solution?.id || null,
      readiness,
      riskControls: [...plan.riskControls],
      priority: {
        rank: 0,
        label: '',
        score,
        reason: `Баллы детерминированно учитывают: ${evidenceReason}; ${signalReason}; ${catalog.reason}; ${solutionReason}. Внешний сигнал не доказывает внутреннюю проблему, а приоритет не является обещанием эффекта.`,
      },
    };
    base.acceptance = buildAcceptanceSuite(base, solution, profile);
    return [{ item: base, score, order }];
  });

  const bestByCategory = new Map();
  for (const candidate of enriched) {
    const previous = bestByCategory.get(candidate.item.category);
    if (!previous || candidate.score > previous.score || (candidate.score === previous.score && candidate.order < previous.order)) {
      bestByCategory.set(candidate.item.category, candidate);
    }
  }

  return [...bestByCategory.values()]
    .sort((left, right) => right.score - left.score || left.order - right.order || CATEGORY_ORDER.get(left.item.category) - CATEGORY_ORDER.get(right.item.category))
    .slice(0, 3)
    .map(({ item }, index) => ({
      ...item,
      priority: { ...item.priority, rank: index + 1, label: priorityLabel(index + 1) },
    }));
}
