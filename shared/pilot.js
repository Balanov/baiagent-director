const OWNERS = {
  revenue: 'Коммерческий владелец процесса и руководитель пилота.',
  cost: 'Владелец операционного процесса и ответственный за контроль качества.',
  offering: 'Владелец продукта/предложения совместно с ответственным за продажи.',
};

export function buildPilotBlueprint(opportunity = {}, solution = null) {
  const language = normalizeLanguage(opportunity.language, 'ru');
  const localized = ANALYSIS_COPY[language]?.pilot;
  if (localized) {
    const category = ['cost', 'revenue', 'offering'].includes(opportunity.category) ? opportunity.category : 'cost';
    return {
      baseline: localized.baseline.replace('{metric}', opportunity.metric || opportunity.businessMetric || ''),
      target: localized.target, period: localized.period, data: localized.data, integrations: localized.integrations,
      owner: opportunity.owner, effectFormula: localized[`${category}Effect`], humanControl: localized.control,
      stopRule: localized.stop, scaleRule: opportunity.decision,
    };
  }
  const requirements = REQUIREMENTS[solution?.id] || DEFAULT_REQUIREMENTS;
  const category = OWNERS[opportunity.category] ? opportunity.category : 'cost';
  const effectFormula = category === 'cost'
    ? 'Эффект = сокращённое время или убытки в деньгах − стоимость пилота и эксплуатации. Объём операций и стоимость часа берём только из данных компании.'
    : category === 'revenue'
      ? 'Эффект = дополнительная маржа от подтверждённого изменения конверсии или продаж − стоимость пилота и эксплуатации.'
      : 'Эффект = дополнительная маржа от подтверждённого изменения предложения − стоимость изменений и эксплуатации.';
  return {
    baseline: `До запуска измерить: ${opportunity.metric || 'текущее время, качество и стоимость операции'}`,
    target: 'Целевое значение согласовать после исходного замера. До этого численный эффект не обещаем.',
    period: '14 дней: исходный замер и эталон → ограниченный пилот → сравнение на сопоставимой выборке.',
    data: requirements.data,
    integrations: requirements.systems,
    owner: OWNERS[category],
    effectFormula,
    humanControl: requirements.control,
    stopRule: 'Остановить при критической ошибке, ухудшении контрольной метрики, нарушении границ доступа или невозможности проверить действие человеком.',
    scaleRule: opportunity.decision || 'Масштабировать только после подтверждения качества и измеримого улучшения выбранной метрики.',
  };
}
